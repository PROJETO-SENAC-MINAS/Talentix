) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
INSERT INTO Org_Membros(ID_Empresas,ID_Usuarios,Papel)
 SELECT e.ID_Empresas,e.ID_Usuarios,'owner' FROM Empresas e
 WHERE e.Ativo=1 AND NOT EXISTS (SELECT 1 FROM Org_Membros m WHERE m.ID_Empresas=e.ID_Empresas AND m.ID_Usuarios=e.ID_Usuarios);
INSERT INTO Org_Membros(ID_Empresas,ID_Usuarios,Papel)
 SELECT r.ID_Empresas,r.ID_Usuarios,'recrutador' FROM Recrutadores r
 WHERE r.Ativo=1 AND NOT EXISTS (SELECT 1 FROM Org_Membros m WHERE m.ID_Empresas=r.ID_Empresas AND m.ID_Usuarios=r.ID_Usuarios);
