CREATE TABLE IF NOT EXISTS Org_Membros (
 ID_Empresas CHAR(36) NOT NULL, ID_Usuarios CHAR(36) NOT NULL, Papel VARCHAR(30) NOT NULL,
 Ativo BOOLEAN NOT NULL DEFAULT 1, Versao INT NOT NULL DEFAULT 1,
 CriadoEm DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(ID_Empresas,ID_Usuarios),
 KEY IX_Org_Usuario(ID_Usuarios,Ativo),
 FOREIGN KEY(ID_Empresas) REFERENCES Empresas(ID_Empresas), FOREIGN KEY(ID_Usuarios) REFERENCES Usuarios(ID_Usuarios)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
